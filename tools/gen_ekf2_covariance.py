#!/usr/bin/env python3
"""Translate the fixed PX4 covariance expressions to allocator-free Rust."""

import argparse
import ast
import hashlib
import os
import re
import subprocess
import sys
from pathlib import Path

from gen_params import DEFAULT_REF, ROOT, git_show, require

SOURCE = "src/modules/ekf2/EKF/python/ekf_derivation/generated/predict_covariance.h"
OUTPUT = ROOT / "src/core/estimator/covariance_generated.rs"


def expression(text, known, functions=None, arrays=None):
    text = re.sub(r"std::pow\((state\(\d+,\s*0\)|_tmp\d+|dt),\s*Scalar\(2\)\)", r"square(\1)", text)
    text = re.sub(r"\bP\((\d+),\s*(\d+)\)", r"p[\1][\2]", text)
    text = re.sub(r"\b(state|accel|accel_var)\((\d+),\s*0\)", r"\1[\2]", text)
    tree = ast.parse(" ".join(text.split()), mode="eval")
    functions = {"square": ("square", 1)} | (functions or {})

    def render(node, parent_precedence=0, right=False):
        if isinstance(node, ast.Constant) and type(node.value) in (int, float):
            return repr(float(node.value))
        if isinstance(node, ast.Name):
            require(node.id in known, f"unknown/forward symbol: {node.id}")
            return node.id
        if isinstance(node, ast.Subscript):
            indices = []
            base = node
            while isinstance(base, ast.Subscript):
                require(isinstance(base.slice, ast.Constant) and type(base.slice.value) is int,
                        "non-literal matrix index")
                indices.insert(0, base.slice.value)
                base = base.value
            require(isinstance(base, ast.Name), "invalid matrix reference")
            bounds = {"p": (24, 24), "state": (25,), "accel": (3,), "accel_var": (3,)}
            bounds.update(arrays or {})
            limits = bounds.get(base.id, ())
            require(len(indices) == len(limits) and bool(limits)
                    and all(0 <= i < limit for i, limit in zip(indices, limits)), "matrix index out of range")
            return base.id + "".join(f"[{index}]" for index in indices)
        if isinstance(node, ast.Call):
            require(isinstance(node.func, ast.Name) and node.func.id in functions, "unsupported symbolic function")
            function, argument_count = functions[node.func.id]
            require(len(node.args) == argument_count and not node.keywords, "unsupported symbolic function arguments")
            return f"{function}({', '.join(render(argument) for argument in node.args)})"
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)):
            sign = "-" if isinstance(node.op, ast.USub) else "+"
            return sign + render(node.operand, 3)
        if isinstance(node, ast.BinOp):
            operations = {ast.Add: ("+", 1), ast.Sub: ("-", 1), ast.Mult: ("*", 2), ast.Div: ("/", 2)}
            require(type(node.op) in operations, "unsupported arithmetic")
            operator, precedence = operations[type(node.op)]
            value = f"{render(node.left, precedence)} {operator} {render(node.right, precedence, True)}"
            if precedence < parent_precedence or (right and precedence == parent_precedence):
                value = f"({value})"
            return value
        raise ValueError(f"unsupported expression node: {type(node).__name__}")

    return render(tree.body)


def render(document):
    require("const matrix::Matrix<Scalar, 25, 1>& state" in document
            and "const matrix::Matrix<Scalar, 24, 24>& P" in document
            and "matrix::Matrix<Scalar, 24, 24> PredictCovariance" in document,
            "unexpected covariance dimensions/signature")
    body = document.split("// Intermediate terms (144)", 1)[1].split("return _res;", 1)[0]
    body = re.sub(r"//[^\n]*", "", body)
    known = {"dt", "gyro_var"}
    terms = []
    outputs = {}
    for statement in body.split(";"):
        statement = statement.strip()
        if not statement or statement in ("matrix::Matrix<Scalar, 24, 24> _res", "_res.setZero()"):
            continue
        temporary = re.fullmatch(r"const Scalar (_tmp\d+)\s*=\s*(.*)", statement, re.S)
        result = re.fullmatch(r"_res\((\d+),\s*(\d+)\)\s*=\s*(.*)", statement, re.S)
        if temporary:
            name, value = temporary.groups()
            require(name == f"_tmp{len(terms)}", "non-sequential/duplicate temporary")
            terms.append(f"    let {name} = {expression(value, known)};")
            known.add(name)
        elif result:
            row, column, value = result.groups()
            key = (int(row), int(column))
            require(0 <= key[0] <= key[1] < 24 and key not in outputs, "invalid/duplicate covariance output")
            outputs[key] = f"    res[{row}][{column}] = {expression(value, known)};"
        else:
            raise ValueError("unsupported covariance statement")
    require(len(terms) == 144 and len(outputs) == 300, "incomplete covariance equations")
    lines = [
        f"// @generated by tools/gen_ekf2_covariance.py from PX4 {DEFAULT_REF}.",
        f"// Source: {SOURCE}",
        f"// Source SHA-256: {hashlib.sha256(document.encode()).hexdigest()}",
        "// Copyright (c) 2015-2023 PX4 Development Team. All rights reserved.",
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// License: tools/px4_msgs/LICENSE; provenance: docs/provenance.md.",
        "// Preserve expression order; do not edit by hand.",
        "", "use super::{math::square, Covariance, StateVector};", "",
        "pub(super) fn predict_covariance(",
        "    state: &StateVector,", "    p: &Covariance,", "    accel: [f32; 3],",
        "    accel_var: [f32; 3],", "    gyro_var: f32,", "    dt: f32,", ") -> Covariance {",
        *terms, "    let mut res = [[0.0; 24]; 24];", *outputs.values(), "    res", "}", "",
    ]
    return subprocess.check_output(["rustfmt", "--edition", "2021", "--emit", "stdout"],
                                   input="\n".join(lines), text=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(os.environ.get("PX4_ROOT", "/home/dev/PX4-Autopilot")))
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        result = render(git_show(args.root, DEFAULT_REF, SOURCE))
        if args.check:
            require(args.output.read_text(encoding="utf-8") == result, "generated covariance drift")
        else:
            args.output.write_text(result, encoding="utf-8", newline="\n")
        print(f"covariance: 144 terms / 300 upper-triangle entries; PX4 {DEFAULT_REF}")
    except (OSError, ValueError, SyntaxError, IndexError, subprocess.CalledProcessError) as error:
        print(f"gen_ekf2_covariance: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
