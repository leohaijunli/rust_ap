#!/usr/bin/env python3
"""Translate the two pinned PX4 EKF-GSF equations with checked matrix bounds."""

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

from gen_params import DEFAULT_REF, ROOT, git_show, require
from gen_ekf2_covariance import expression

DIRECTORY = "src/modules/ekf2/EKF/yaw_estimator/derivation/generated"
OUTPUT = ROOT / "src/core/estimator/gsf_generated.rs"


def scalar(value, known):
    value = value.replace("std::cos", "cos").replace("std::sin", "sin")
    value = re.sub(r"Scalar\(([\d.]+)\)", r"\1", value)
    value = re.sub(r"std::pow\(([^,()]+),\s*2\)", r"square(\1)", value)
    value = re.sub(r"std::pow\(state\(2,\s*0\),\s*2\)", "square(state(2, 0))", value)
    value = value.replace("math::min<Scalar>(0, (((_tmp2) > 0) - ((_tmp2) < 0)))", "negative_sign(_tmp2)")
    value = re.sub(r"d_vel\((\d+),\s*0\)", r"d_vel[\1]", value)
    return expression(value, known, functions={"cos": ("libm::cosf", 1), "sin": ("libm::sinf", 1),
        "negative_sign": ("negative_sign", 1)}, arrays={"p": (3, 3), "state": (3,), "d_vel": (2,)})


def render(documents):
    lines = [f"// @generated by tools/gen_ekf2_gsf.py from PX4 {DEFAULT_REF}.",
        "// Copyright (c) 2020-2024 PX4 Development Team. All rights reserved.",
        "// SPDX-License-Identifier: BSD-3-Clause; license: tools/px4_msgs/LICENSE.",
        "use super::math::square;", "type Matrix3 = [[f32; 3]; 3];",
        "pub(super) struct VelocityUpdate { pub inverse: [[f32; 2]; 2], pub determinant_inverse: f32, pub gain: [[f32; 2]; 3], pub covariance: Matrix3 }"]
    for kind, document in documents.items():
        lines.append(f"// Source: {DIRECTORY}/yaw_est_{kind}.h; SHA-256 {hashlib.sha256(document.encode()).hexdigest()}")
        parts = document.split("// Intermediate terms", 1)[1].split("// Output terms", 1)
        if kind == "predict_covariance":
            lines.append("pub(super) fn predict(state: &[f32; 3], p: &Matrix3, d_vel: [f32; 2], d_vel_var: f32, d_ang: f32, d_ang_var: f32) -> Matrix3 {")
            known = {"d_vel_var", "d_ang", "d_ang_var"}
        else:
            lines.append("pub(super) fn update(p: &Matrix3, vel_obs_var: f32, epsilon: f32) -> VelocityUpdate {")
            known = {"vel_obs_var", "epsilon"}
        terms = re.findall(r"const Scalar (_tmp\d+)\s*=\s*(.*?);", parts[0], re.S)
        require(len(terms) == (8 if kind == "predict_covariance" else 15), "incomplete GSF temporaries")
        for index, (name, value) in enumerate(terms):
            require(name == f"_tmp{index}", "invalid GSF temporary sequence")
            lines.append(f"    let {name} = {scalar(value, known)};")
            known.add(name)
        if kind == "predict_covariance":
            lines.append("    let mut res = [[0.0; 3]; 3];")
            outputs = {"_res": ("res", (3, 3), 6)}
        else:
            lines.extend(["    let mut inverse = [[0.0; 2]; 2];", "    let mut gain = [[0.0; 2]; 3];", "    let mut covariance = [[0.0; 3]; 3];"])
            outputs = {"_s_inv": ("inverse", (2, 2), 4), "_k": ("gain", (3, 2), 6), "_p_new": ("covariance", (3, 3), 6)}
        for source, (target, dimensions, count) in outputs.items():
            values = re.findall(rf"{source}\((\d+),\s*(\d+)\)\s*=\s*(.*?);", parts[1], re.S)
            require(len(values) == count and len({(i, j) for i, j, _ in values}) == count, "incomplete GSF output")
            for i, j, value in values:
                require(int(i) < dimensions[0] and int(j) < dimensions[1], "GSF index out of range")
                lines.append(f"    {target}[{i}][{j}] = {scalar(value, known)};")
        if kind == "predict_covariance": lines.append("    res")
        else:
            result = re.search(r"^\s*_s_det_inv\s*=\s*(.*?);", parts[1], re.M | re.S)
            require(result is not None, "missing GSF determinant inverse")
            lines.append(f"    VelocityUpdate {{ inverse, determinant_inverse: {scalar(result[1], known)}, gain, covariance }}")
        lines.append("}")
    lines.append("fn negative_sign(value: f32) -> f32 { if value < 0.0 { -1.0 } else { 0.0 } }")
    return subprocess.check_output(["rustfmt", "--edition", "2021", "--emit", "stdout"], input="\n".join(lines), text=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("/home/dev/PX4-Autopilot"))
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        result = render({kind: git_show(args.root, DEFAULT_REF, f"{DIRECTORY}/yaw_est_{kind}.h")
            for kind in ("predict_covariance", "compute_measurement_update")})
        if args.check: require(args.output.read_text(encoding="utf-8") == result, "GSF equations drift")
        else: args.output.write_text(result, encoding="utf-8", newline="\n")
        print("GSF: fixed covariance and measurement update equations")
    except (OSError, ValueError, SyntaxError, subprocess.CalledProcessError) as error:
        print(f"gen_ekf2_gsf: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
