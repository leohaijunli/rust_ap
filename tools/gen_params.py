#!/usr/bin/env python3
"""Generate the EKF2 parameter catalog from fixed PX4 v1.17.0 YAML."""

import argparse
import json
import math
import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REF = "d6f12ad1c4f70ad3230afd7d86e971421e02fef4"
EKF2_DIR = "src/modules/ekf2"
DEFAULT_OUTPUT = ROOT / "src/core/estimator/params_generated.rs"

KINDS = {
    "float": "Float",
    "int32": "Int32",
    "boolean": "Boolean",
    "enum": "Enum",
    "bitmask": "Bitmask",
}

@dataclass(frozen=True)
class Definition:
    name: str
    kind: str
    default: int | float
    minimum: float | None
    maximum: float | None
    unit: str
    support: str


def require(condition, message):
    if not condition:
        raise ValueError(message)


def git_show(root, ref, path):
    return subprocess.check_output(
        ["git", "-C", str(root), "show", f"{ref}:{path}"],
        text=True,
        stderr=subprocess.PIPE,
    )


def yaml_paths(root, ref):
    files = subprocess.check_output(
        ["git", "-C", str(root), "ls-tree", "-r", "--name-only", ref, EKF2_DIR],
        text=True,
    ).splitlines()
    paths = [
        path
        for path in files
        if path == f"{EKF2_DIR}/module.yaml"
        or (path.startswith(f"{EKF2_DIR}/params_") and path.endswith(".yaml"))
    ]
    paths.sort()
    require(paths, f"no EKF2 parameter YAML under {ref}:{EKF2_DIR}")
    return paths


def load_documents(root, ref):
    import yaml

    documents = []
    for path in yaml_paths(root, ref):
        documents.append((path, yaml.safe_load(git_show(root, ref, path))))
    return documents


def parse_definition(name, meta):
    require(isinstance(name, str) and name, "parameter name is empty")
    require(len(name) <= 16, f"{name}: name exceeds MAVLink param_id limit")
    require(
        all(byte.isupper() or byte.isdigit() or byte == "_" for byte in name),
        f"{name}: name is not MAVLink parameter style",
    )
    kind = KINDS.get(meta.get("type"))
    require(kind, f"{name}: unsupported parameter type {meta.get('type')!r}")
    raw_default = meta.get("default")
    require(raw_default is not None, f"{name}: missing default")
    if kind == "Float":
        default = float(raw_default)
        require(math.isfinite(default), f"{name}: non-finite default")
    else:
        default = int(raw_default)
    minimum = meta.get("min")
    maximum = meta.get("max")
    return Definition(
        name=name,
        kind=kind,
        default=default,
        minimum=None if minimum is None else float(minimum),
        maximum=None if maximum is None else float(maximum),
        unit=str(meta.get("unit", "")),
        support="Planned",
    )


def collect(documents):
    definitions = []
    seen = {}
    for path, document in documents:
        require(isinstance(document, dict), f"{path}: YAML root is not a mapping")
        for group in document.get("parameters", []):
            for name, meta in group.get("definitions", {}).items():
                require(name not in seen, f"{name}: duplicate in {path} and {seen.get(name)}")
                seen[name] = path
                definitions.append(parse_definition(name, meta))
    require(definitions, "no EKF2 parameters found")
    return definitions


def float_literal(value):
    require(math.isfinite(value), "non-finite float literal")
    if value == int(value) and abs(value) < 1e16:
        return f"{int(value)}.0"
    return repr(value)


def rust_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(definitions, ref):
    lines = [
        f"// @generated by tools/gen_params.py from PX4-Autopilot {ref}.",
        "// Source: src/modules/ekf2/module.yaml + params_*.yaml (BSD-3-Clause).",
        "// Copyright (c) 2012 - 2023, PX4 Development Team. All rights reserved.",
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// License: tools/px4_msgs/LICENSE; provenance: docs/provenance.md.",
        "// Do not edit by hand; run tools/gen_params.py --check in CI.",
        "",
        "use super::{ParamDef, ParamKind, ParamValue, Support};",
        "",
        "pub static EKF2_PARAMS: &[ParamDef] = &[",
    ]
    for definition in definitions:
        if definition.kind == "Float":
            default = f"ParamValue::Float({float_literal(definition.default)})"
        else:
            default = f"ParamValue::Int({definition.default})"
        minimum = (
            "None"
            if definition.minimum is None
            else f"Some({float_literal(definition.minimum)})"
        )
        maximum = (
            "None"
            if definition.maximum is None
            else f"Some({float_literal(definition.maximum)})"
        )
        lines.append(
            "    ParamDef {\n"
            f'        name: {rust_string(definition.name)},\n'
            f"        kind: ParamKind::{definition.kind},\n"
            f"        default: {default},\n"
            f"        min: {minimum},\n"
            f"        max: {maximum},\n"
            f'        unit: {rust_string(definition.unit)},\n'
            f"        support: Support::{definition.support},\n"
            "    },"
        )
    lines.extend(["];", ""])
    return "\n".join(lines)


def render_help(documents, ref):
    """Freeze source descriptions/options, never runtime values or limits."""
    entries = {}
    for path, document in documents:
        for group in document.get("parameters", []):
            for name, meta in group.get("definitions", {}).items():
                require(name not in entries, f"{name}: duplicate help entry")
                short = " ".join(meta.get("description", {}).get("short", "").split())
                require(short, f"{name}: missing parameter description")
                options = meta.get("bit" if meta["type"] == "bitmask" else "values", {})
                entries[name] = {
                    "type": meta["type"],
                    "shortDesc": short,
                    "options": {str(key): str(value) for key, value in options.items()},
                }
    return json.dumps({
        "version": 1,
        "source": "PX4-Autopilot EKF2 YAML",
        "ref": ref,
        "license": "BSD-3-Clause",
        "sourceFiles": [path for path, _ in documents],
        "parameters": entries,
    }, indent=2, ensure_ascii=False) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(os.environ.get("PX4_ROOT", "/home/dev/PX4-Autopilot")),
        help="PX4-Autopilot checkout (default: $PX4_ROOT or /home/dev/PX4-Autopilot)",
    )
    parser.add_argument("--ref", default=DEFAULT_REF, help="fixed PX4 git ref")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--help-output", type=Path, help="Also generate/check descriptive EKF2 help JSON")
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the checked-in table differs from the generated table",
    )
    args = parser.parse_args()

    try:
        documents = load_documents(args.root, args.ref)
        definitions = collect(documents)
        rendered = render(definitions, args.ref)
        help_text = render_help(documents, args.ref) if args.help_output else None
    except (OSError, subprocess.CalledProcessError, ValueError) as error:
        print(f"gen_params: {error}", file=sys.stderr)
        return 1

    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except OSError as error:
            print(f"gen_params: {error}", file=sys.stderr)
            return 1
        if current != rendered:
            print(f"gen_params: {args.output} is out of date", file=sys.stderr)
            return 1
        if args.help_output and (
                not args.help_output.exists()
                or args.help_output.read_text(encoding="utf-8") != help_text):
            print(f"gen_params: {args.help_output} is out of date", file=sys.stderr)
            return 1
        print(f"gen_params: {len(definitions)} parameters up to date")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    if args.help_output:
        args.help_output.parent.mkdir(parents=True, exist_ok=True)
        args.help_output.write_text(help_text, encoding="utf-8", newline="\n")
    print(f"gen_params: wrote {len(definitions)} parameters to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
