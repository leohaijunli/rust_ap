#!/usr/bin/env python3
"""Generate typed runtime IDs; values/limits still come from the unique EKF catalog."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/core/estimator/runtime_parameter_table.rs"


def generated():
    source = (ROOT / "src/core/estimator/params_generated.rs").read_text(encoding="utf-8")
    catalog = re.findall(r'name: "(EKF2_[A-Z0-9_]+)",\s*kind: ParamKind::(\w+)', source)
    names = [name for name, _ in catalog]
    if len(names) != 142 or len(set(names)) != 142:
        raise ValueError("runtime table requires the fixed 142-entry EKF catalog")
    idents = ["".join(part.title() for part in name.split("_")) for name in names]
    entries = [
        f"                {ident}: {index} => {name.lower()}: {'Real' if kind == 'Float' else 'Integer'},"
        for index, (ident, (name, kind)) in enumerate(zip(idents, catalog))
    ]
    # The ownership list is generated too: a hand-written predicate would drift
    # from the catalog as soon as a parameter is added or removed.
    owned = " | ".join(f"Id::{ident}" for ident in idents)
    return "\n".join([
        "// @generated by tools/gen_ekf2_runtime_params.py; IDs only, no copied defaults.",
        "// Values and limits use estimator::EKF2_PARAMS (fixed PX4 v1.17.0).",
        "macro_rules! with_ekf2_parameters {",
        "    (base { $($base:tt)* } link { $($link:tt)* }) => {",
        "        parameter_table! { base { $($base)* } ekf {", *entries,
        "        } link { $($link)* } }", "",
        "        /// True for the fixed EKF2 catalog ids generated above.",
        "        pub const fn is_ekf2_parameter(id: Id) -> bool {",
        f"            matches!(id, {owned})",
        "        }",
        "    };", "}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("EKF runtime IDs differ; regenerate and review")
    else:
        with OUTPUT.open("w", encoding="utf-8", newline="\n") as output:
            output.write(text)


if __name__ == "__main__":
    main()
